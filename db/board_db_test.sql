-- =========================================================================
-- 1번 – 조건 검색 (LIKE)
-- 이메일(또는 아이디) 끝부분이 특정 문자열로 끝나는 회원을 조회하세요.
-- =========================================================================
SELECT * FROM member
WHERE email LIKE '%net';

-- =========================================================================
-- 2번 – 날짜 범위 조회
-- 최근 며칠 이내에 작성된 게시글을 최신순으로 조회하세요.
-- =========================================================================
SELECT * FROM post
ORDER BY write_date DESC; -- post 테이블 데이터 삽입이 동시에 이루어져서 큰 변화는 없음

-- =========================================================================
-- 3번 – 글을 한 번도 안 쓴 회원 찾기
-- 게시글을 작성한 적이 없는 회원을 조회하세요.
-- =========================================================================
SELECT m.nickname 
FROM member m
LEFT JOIN post p
	ON m.member_id = p.member_id
WHERE p.post_id IS NULL;

-- =========================================================================
-- 4번 – 댓글이 하나도 없는 게시글 찾기
-- 댓글이 한 개도 달리지 않은 게시글의 제목과 작성자 이름을 조회하세요.
-- =========================================================================
SELECT p.title, p.contents, c.comment_id
FROM post p
LEFT JOIN comment c
	ON p.post_id = c.post_id
WHERE c.comment_id IS NULL;

-- =========================================================================
-- 5번 – 3개 테이블 조인
-- 게시글 제목, 작성자 이름, 댓글 내용, 댓글 작성자 이름을 함께 조회하세요.
-- =========================================================================
SELECT p.title, m.nickname, c.contents, c.member_id  
FROM member m
JOIN post p
	ON m.member_id = p.member_id
JOIN comment c
	ON p.post_id = c.post_id;

-- =========================================================================
-- 6번 – 서브쿼리로 평균 이상 필터링
-- 평균 댓글 수보다 댓글이 많이 달린 게시글을 조회하세요.
-- =========================================================================
SELECT post_id, COUNT(*) AS comment_count
FROM comment
GROUP BY post_id
HAVING COUNT(*) > (
    SELECT AVG(comment_count)
    FROM (
        SELECT post_id, COUNT(*) AS comment_count
        FROM comment
        GROUP BY post_id
    ) t
);

-- =========================================================================
-- 7번 – 자기 게시글에 자기가 댓글 단 경우 찾기
-- 본인이 작성한 게시글에 본인이 직접 댓글을 단 사례를 조회하세요.
-- =========================================================================
SELECT * FROM post p
JOIN comment c
	ON p.member_id = c.member_id
	AND p.post_id = c.post_id;

-- =========================================================================
-- 8번 – 문자열 함수로 그룹화
-- 이메일(또는 특정 텍스트 컬럼)의 일부를 잘라 기준으로 그룹화하고 인원수를 조회하세요.
-- =========================================================================
SELECT SUBSTRING_INDEX(email, '@', -1) AS `도메인`, COUNT(*) AS `인원수`
FROM member
GROUP BY SUBSTRING_INDEX(email, '@', -1);

-- =========================================================================
-- 9번 – 페이징 (LIMIT + OFFSET)
-- 게시글을 정렬한 뒤, 특정 페이지 구간(예: 2페이지, 페이지당 3개)만 조회하세요.
-- =========================================================================
SELECT *
FROM post
ORDER BY post_id
LIMIT 3 OFFSET 3;

-- =========================================================================
-- 10번 – 존재 여부 확인 (EXISTS)
-- 댓글을 한 번이라도 작성한 적 있는 회원을 조회하세요.
-- =========================================================================
SELECT * FROM member m
WHERE EXISTS (SELECT 1 FROM comment c WHERE c.member_id = m.member_id);